const esc = (s: string): string => s.replace(/[&<>"]/g, (c) => `&#${c.charCodeAt(0)};`);
const hex = (n: number): string => `#${n.toString(16).padStart(6, '0')}`;

/** A friendly drawn portrait from a few colours: no image files needed. */
export function portraitSvg(p: PortraitSpec, label: string): string {
  const hat =
    p.hat !== null
      ? `<path d="M14 24c1-9 8-13 18-13s17 4 18 13z" fill="${hex(p.hat)}"/><rect x="11" y="23" width="42" height="4" rx="2" fill="${hex(p.hat)}" opacity=".85"/>`
      : `<path d="M15 26c0-11 7-16 17-16s17 5 17 16c-4-5-9-7-17-7s-13 2-17 7z" fill="${hex(p.hair)}"/>`;
  const glasses = p.glasses
    ? `<g fill="none" stroke="#2a2220" stroke-width="1.6"><circle cx="25" cy="33" r="4.6"/><circle cx="39" cy="33" r="4.6"/><path d="M29.6 33h4.8"/></g>`
    : '';
  return `<svg class="portrait" viewBox="0 0 64 64" role="img" aria-label="${esc(label)}">
    <circle cx="32" cy="32" r="31" fill="#2c4a7a" opacity=".35"/>
    <path d="M8 62c2-13 11-18 24-18s22 5 24 18z" fill="${hex(p.scarf)}"/>
    <rect x="27" y="40" width="10" height="8" rx="3" fill="${hex(p.skin)}"/>
    <ellipse cx="32" cy="31" rx="15" ry="16" fill="${hex(p.skin)}"/>
    ${hat}${glasses}
    <circle cx="26" cy="33" r="1.5" fill="#2a2220"/><circle cx="38" cy="33" r="1.5" fill="#2a2220"/>
    <path d="M26 41q6 5 12 0" fill="none" stroke="#7d3a2e" stroke-width="1.8" stroke-linecap="round"/>
  </svg>`;
}

