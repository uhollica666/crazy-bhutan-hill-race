export interface BriefingModel {
  level: LevelDef;
  story: LevelStory;
  cast: CastMember[];
  vehicleName: string;
  conditions: string;
  /** Restarts and replays use this to make the screen quick to dismiss. */
  repeat: boolean;
}

/** The pre-mission story card. Data-driven (see src/data/story), skippable with one tap, and never shown on restart. */
export class BriefingScreen {
  readonly el: HTMLElement;
  private onGo: (() => void) | null = null;
  private onSkip: (() => void) | null = null;

  constructor(private readonly d: InfoDeps) {
    const el = (this.el = document.createElement('div'));
    el.className = 'modal briefing';
    el.id = 'screen-briefing';
    el.dataset.screen = '1';
    el.hidden = true;
    el.setAttribute('role', 'dialog');
    el.setAttribute('aria-modal', 'true');
    el.setAttribute('aria-labelledby', 'brief-title');
    d.host.appendChild(el);
    el.addEventListener('keydown', (e) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        this.finish(true);
      }
    });
  }

  get isOpen(): boolean {
    return !this.el.hidden;
  }

  show(m: BriefingModel, onGo: () => void, onSkip: () => void): void {
    this.onGo = onGo;
    this.onSkip = onSkip;
    const people = m.cast
      .map(
        (c) =>
          `<figure class="cast">${portraitSvg(c.portrait, c.name)}<figcaption><b>${esc(c.name)}</b><span>&ldquo;${esc(c.line)}&rdquo;</span></figcaption></figure>`,
      )
      .join('');
    const li = (items: string[]): string => items.map((t) => `<li>${esc(t)}</li>`).join('');
    const q = m.story.quick;
    const quick = [
      ['t-problem', 'The problem', q.problem, ICON_WARN],
      ['t-goal', 'The job', q.goal, ICON_FLAG],
      ['t-challenge', 'The challenge', q.challenge, ICON_BOLT],
    ]
      .map(([cls, label, text, icon]) => `<li class="${cls}">${icon}<b>${label}</b><span>${esc(text)}</span></li>`)
      .join('');
    this.el.innerHTML = `<div class="panel wide brief-panel">
      <header class="brief-hero"><div class="eyebrow">${esc(m.story.stamp)} &middot; ${esc(m.level.name)}</div>
        <h2 id="brief-title">${esc(m.story.headline)}</h2></header>
      <div class="brief-body">
        ${people ? `<div class="brief-cast">${people}</div>` : ''}
        <ul class="brief-quick">${quick}</ul>
        <details class="brief-more"><summary>Read the full story</summary>
          <div class="brief-text">${m.story.text.map((t) => `<p>${esc(t)}</p>`).join('')}</div>
          <div class="brief-cols">
            <div><h3>Your job</h3><ul>${li(m.story.objectives)}</ul></div>
            <div><h3>Watch out</h3><ul>${li(m.story.watchOut)}</ul></div></div></details>
        <p class="brief-meta">Driving the ${esc(m.vehicleName)} &middot; ${esc(m.conditions)}</p>
        <div class="brief-actions">
          <button class="btn primary" type="button" id="brief-go">${ICON_PLAY}<span>${m.repeat ? 'Go' : 'Start the drive'}</span></button>
          <button class="btn ghost" type="button" id="brief-skip">Skip story</button></div></div></div>`;
    this.el.querySelector('#brief-go')?.addEventListener('click', () => {
      this.d.click();
      this.finish(false);
    });
    this.el.querySelector('#brief-skip')?.addEventListener('click', () => {
      this.d.click(true);
      this.finish(true);
    });
    this.el.hidden = false;
    requestAnimationFrame(() =>
      this.el.querySelector<HTMLElement>('#brief-go')?.focus({ preventScroll: true }),
    );
  }

  /** Same as pressing "Skip story". */
  skip(): void {
    this.finish(true);
  }

  private finish(skipped: boolean): void {
    if (this.el.hidden) return;
    this.el.hidden = true;
    const cb = skipped ? this.onSkip : this.onGo;
    this.onGo = this.onSkip = null;
    cb?.();
  }

  hide(): void {
    this.el.hidden = true;
    this.onGo = this.onSkip = null;
  }

  dispose(): void {
    this.el.remove();
  }
}

const ICON_PLAY =
  '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M7 4.5l12 7.5-12 7.5z" fill="currentColor" stroke="none"/></svg>';

const svgIcon = (d: string): string =>
  `<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">${d}</svg>`;
const ICON_WARN = svgIcon('<path d="M12 3l10 18H2z"/><path d="M12 10v5M12 18h.01"/>');
const ICON_FLAG = svgIcon('<path d="M5 21V4M5 4h12l-2.5 4L17 12H5"/>');
const ICON_BOLT = svgIcon('<path d="M13 2L4 14h7l-1 8 9-12h-7z"/>');
